BEGIN;

-- ----------------------------------------------------------------
-- 1. ID 609: Бордюр дорожный попал в категорию «Плитка меланж гранит»
--    Правка: category → 'Бордюры и поребрики', unit → 'шт'
-- ----------------------------------------------------------------
UPDATE items
SET
    category = 'Бордюры и поребрики',
    unit     = 'шт'
WHERE id = 609
  AND name ILIKE '%бордюр%меланж гранит осень 2 сорт%';

-- ----------------------------------------------------------------
-- 2. ID 620: Поребрик с неверной формой (mold_id=17 — форма ПАРКЕТ)
--    Правка: mold_id → 20 (форма поребрика)
-- ----------------------------------------------------------------
UPDATE items
SET mold_id = 20
WHERE id = 620
  AND name ILIKE '%поребрик%меланж гладкий осень 2 сорт%';

-- ----------------------------------------------------------------
-- 3. ID 607: Вес СИТИ-МИКС 8мм Гладкая Серая Эксперим. = 15.11 кг/кв.м
--    Должно быть ~151.11 (как у Меланж-версии той же формы)
-- ----------------------------------------------------------------
UPDATE items
SET weight_kg = 151.110000
WHERE id = 607
  AND name ILIKE '%сити-микс%1.см.8%гладкая серая%эксперем%';

-- ----------------------------------------------------------------
-- 4. ID 647: Опечатка — слитное написание "Коричневая2 сорт"
-- ----------------------------------------------------------------
UPDATE items
SET name = 'Тротуарная плитка КЛАССИКО - 2.КО.6 60мм Гладкая Коричневая 2 сорт'
WHERE id = 647
  AND name LIKE '%Коричневая2 сорт%';

-- ----------------------------------------------------------------
-- 5. ID 644: Опечатка — "ПРЯМОУГОЛЬНИК- 2.П.4" (лишний пробел перед тире)
-- ----------------------------------------------------------------
UPDATE items
SET name = 'Тротуарная плитка ПРЯМОУГОЛЬНИК - 2.П.4 40мм Гладкая Красная 2 сорт'
WHERE id = 644
  AND name LIKE '%ПРЯМОУГОЛЬНИК-%';

-- ----------------------------------------------------------------
-- 6. ID 628: Артикул 2-сортного формата у экспериментальной позиции
--    'PL-2522S' → 'PL-252E' (E = Experimental)
-- ----------------------------------------------------------------
UPDATE items
SET article = 'PL-252E'
WHERE id = 628
  AND article = 'PL-2522S'
  AND name ILIKE '%эксперем%';

-- ----------------------------------------------------------------
-- 7. Массовое исправление опечатки «Эксперементальная» → «Экспериментальная»
--    (8 позиций из 14 экспериментальных)
-- ----------------------------------------------------------------
UPDATE items
SET name = REPLACE(name, 'Эксперементальная', 'Экспериментальная')
WHERE name ILIKE '%Эксперементальная%'
  AND category IN (
    'Бордюры и поребрики','Плитка гладкая','Плитка гранитная',
    'Плитка меланж гладкая','Плитка меланж гранит'
  );

-- ----------------------------------------------------------------
-- Проверка: вывести изменённые строки
-- ----------------------------------------------------------------
SELECT id, name, category, unit, weight_kg, mold_id, article
FROM items
WHERE id IN (607, 609, 620, 628, 644, 647)
   OR name ILIKE '%Экспериментальная%'
ORDER BY id;

COMMIT;
